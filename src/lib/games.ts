const LEGACY_ALIAS_MAP: Record<string, string> = {
  ball: "bouncing-ball-circle",
  breaker: "ring-escape",
  marble: "country-marble-race",
  crusher: "hydraulic-press",
  sand: "kinetic-sand-waterfall",
  vortex: "cosmic-gravity-vortex",
};

export function getGameById(id: string | null | undefined): GameDefinition {
  if (!id) return GAMES_REGISTRY[0];
  const resolved = LEGACY_ALIAS_MAP[id] || id;
  return GAMES_REGISTRY.find((g) => g.id === resolved) || GAMES_REGISTRY[0];
}

export function getGamesByCategory(categoryId: string): GameDefinition[] {
  if (categoryId === "all") return GAMES_REGISTRY;
  return GAMES_REGISTRY.filter((g) => g.category === categoryId);
}
